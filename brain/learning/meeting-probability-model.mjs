const MINIMUM_CALIBRATION_SAMPLES=10;
const MINIMUM_BIN_SAMPLES=5;
const PRIOR_STRENGTH=10;

const round=(value,digits=4)=>Number(Number(value).toFixed(digits));
const clamp01=value=>Math.max(0,Math.min(1,Number(value)));

function requiredNumber(name,value,{min,max}){
  if(value===null||value===undefined||value==='') throw new Error(`${name} is required`);
  const numeric=Number(value);
  if(!Number.isFinite(numeric)||numeric<min||numeric>max) throw new Error(`${name} must be between ${min} and ${max}`);
  return numeric;
}

function matchingBin(probability,bins=[]){
  return (Array.isArray(bins)?bins:[]).find(bin=>{
    const min=Number(bin?.min_probability);
    const max=Number(bin?.max_probability);
    if(!Number.isFinite(min)||!Number.isFinite(max)||max<=min) return false;
    return probability>=min&&(probability<max||(max>=1&&probability<=max));
  })||null;
}

export function estimateMeetingProbability({
  opportunityScore,
  confidence,
  calibrationMetrics=null,
  minimumCalibrationSamples=MINIMUM_CALIBRATION_SAMPLES,
  minimumBinSamples=MINIMUM_BIN_SAMPLES,
  priorStrength=PRIOR_STRENGTH,
}={}){
  const score=requiredNumber('opportunityScore',opportunityScore,{min:0,max:100});
  const certainty=requiredNumber('confidence',confidence,{min:0,max:1});
  const raw=round((score/100)*certainty);
  const sampleSize=Math.max(0,Number(calibrationMetrics?.sample_size)||0);
  const reasons=[`bootstrap = opportunity_score(${round(score/100)}) × confidence(${round(certainty)})`];

  const baseCalibration={
    applied:false,
    sample_size:sampleSize,
    minimum_sample_size:minimumCalibrationSamples,
    minimum_bin_sample_size:minimumBinSamples,
    prior_strength:priorStrength,
    bin_sample_size:0,
    reliability_weight:0,
  };

  if(sampleSize<minimumCalibrationSamples){
    reasons.push(`empirical calibration deferred: ${sampleSize}/${minimumCalibrationSamples} settled outcomes`);
    return Object.freeze({
      schema_version:'powerhouse.meeting-probability-estimate.v1',
      model_version:'meeting-probability-v1',
      source:'bootstrap_proxy',
      raw_probability:raw,
      probability:raw,
      calibration:Object.freeze(baseCalibration),
      reasons:Object.freeze(reasons),
    });
  }

  const bin=matchingBin(raw,calibrationMetrics?.calibration_bins);
  const binSamples=Math.max(0,Number(bin?.sample_size)||0);
  const actualRate=Number(bin?.actual_positive_rate);
  if(!bin||binSamples<minimumBinSamples||!Number.isFinite(actualRate)||actualRate<0||actualRate>1){
    reasons.push('empirical calibration deferred: matching bin evidence is insufficient');
    return Object.freeze({
      schema_version:'powerhouse.meeting-probability-estimate.v1',
      model_version:'meeting-probability-v1',
      source:'bootstrap_proxy',
      raw_probability:raw,
      probability:raw,
      calibration:Object.freeze({...baseCalibration,bin_sample_size:binSamples}),
      reasons:Object.freeze(reasons),
    });
  }

  const reliability=round(binSamples/(binSamples+Math.max(1,Number(priorStrength)||PRIOR_STRENGTH)));
  const calibrated=round(clamp01((raw*(1-reliability))+(actualRate*reliability)));
  reasons.push(`matching calibration bin: n=${binSamples}, actual_rate=${round(actualRate)}, reliability=${reliability}`);
  reasons.push(`calibrated = raw × ${round(1-reliability)} + empirical × ${reliability}`);
  return Object.freeze({
    schema_version:'powerhouse.meeting-probability-estimate.v1',
    model_version:'meeting-probability-v1',
    source:'empirical_bin_calibration',
    raw_probability:raw,
    probability:calibrated,
    calibration:Object.freeze({
      ...baseCalibration,
      applied:true,
      bin_sample_size:binSamples,
      reliability_weight:reliability,
      bin_min_probability:Number(bin.min_probability),
      bin_max_probability:Number(bin.max_probability),
      bin_actual_positive_rate:round(actualRate),
    }),
    reasons:Object.freeze(reasons),
  });
}


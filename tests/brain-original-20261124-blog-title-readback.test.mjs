import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const url="https://www.bedrijfsgeheugen.nl/blog/voorbereid-op-een-mogelijke-twinfield-api-hoe-je-als-mkb-je-boekhoudin/";
const title="Bankverschillen oplossen met Twinfield: praktische controle";
const oldTitle="Bankverschillen oplossen: wat verandert er voor jou?";
const article=readFileSync("blog/voorbereid-op-een-mogelijke-twinfield-api-hoe-je-als-mkb-je-boekhoudin/index.html",'utf8');
const index=readFileSync('blog/index.html','utf8');
const rss=readFileSync('blog/rss.xml','utf8');
const translation=JSON.parse(readFileSync("config/bg-static-i18n-en.d/powerhouse-blog-2026-11-24.json",'utf8'));
test('same canonical 24-Nov article uses exact source-rendered topic across all title fields',()=>{
  const py=spawnSync('python3',['-c',"import importlib.util\ns=importlib.util.spec_from_file_location('publisher','tools/site-shell/publish_powerhouse_blog_artifact.py'); m=importlib.util.module_from_spec(s); s.loader.exec_module(m)\nd={'title':'Bankverschillen oplossen met Twinfield: praktische controle op betaalreferenties en openstaande facturen','focus_keyword':'Bankverschillen oplossen','body':'Bankverschillen oplossen met Twinfield en betaalreferenties.'}\nprint(m.seo_title(d['title'],m.seo_focus(d)))"],{encoding:'utf8'});
  assert.equal(py.status,0,py.stderr);
  assert.equal(py.stdout.trim(),title);
  assert.ok(title.length<=60);
  assert.ok(article.includes('<title>'+title+'</title>'));
  assert.ok(article.includes('<h1>'+title+'</h1>'));
  assert.ok(article.includes('property="og:title" content="'+title+'"'));
  const ld=JSON.parse(article.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1]);
  const post=ld['@graph'].find(x=>x['@type']==='BlogPosting');
  assert.equal(post.headline,title);
  assert.equal(post.mainEntityOfPage,url);
  assert.equal(post.datePublished,'2026-11-24');
  assert.equal(article.includes(oldTitle),false);
  const cards=index.split('<a class="kaart"').filter(x=>x.includes('href="'+url+'"'));
  assert.equal(cards.length,1);
  assert.ok(cards[0].includes('<h2>'+title+'</h2>'));
  const items=rss.match(/<item>[\s\S]*?<\/item>/g).filter(x=>x.includes('<guid>'+url+'</guid>'));
  assert.equal(items.length,1);
  assert.ok(items[0].includes('<title>'+title+'</title>'));
  assert.ok(items[0].includes('<pubDate>Tue, 24 Nov 2026 15:52:38 +0000</pubDate>'));
  assert.equal(translation[title],"Resolving bank discrepancies with Twinfield: practical checks");
  assert.equal(Object.hasOwn(translation,oldTitle),false);
});

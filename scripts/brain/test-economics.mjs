import {routeCompute} from '../../brain/economics/router.mjs';
import {missionBudget,costPerOutcome,detectCostAnomaly} from '../../brain/economics/budget.mjs';
if(routeCompute({cache_hit:true}).tier!=='CACHE') throw new Error('cache not first');
if(routeCompute({deterministic_possible:true}).tier!=='DETERMINISTIC') throw new Error('deterministic not preferred');
if(routeCompute({expected_value:5,confidence:.7,needs_reasoning:true}).tier==='LARGE_MODEL') throw new Error('low-value escalated');
if(!['SMALL_MODEL','LARGE_MODEL'].includes(routeCompute({expected_value:500,confidence:.4,needs_reasoning:true,complexity:.9}).tier)) throw new Error('high value cannot reason');
const b=missionBudget({expected_value:100,confidence:.8}); if(!(b.max_credits>0&&b.max_retries===2)) throw new Error('budget bad');
if(costPerOutcome({cost:20,useful_outcomes:4})!==5) throw new Error('cost per outcome');
if(!detectCostAnomaly({credits_per_run:100,baseline_credits_per_run:10,retry_count:8}).anomaly) throw new Error('cost anomaly missed');
console.log('economics tests passed');
